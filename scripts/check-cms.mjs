import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';

const base='http://127.0.0.1:3000';
const admin=JSON.parse(await readFile('.data/local-admin.json','utf8'));
const request=async(route,options={})=>{
  const response=await fetch(base+route,options);
  const result=await response.json();
  return {response,result};
};
const post=(data)=>({method:'POST',headers:{'Content-Type':'application/json','Origin':base},body:JSON.stringify(data)});
const login=await request('/cms-api/users/login',post(admin));
assert.equal(login.response.status,200);
assert.ok(login.result.token);
const authorization={Authorization:`JWT ${login.result.token}`};
const itineraries=await request('/cms-api/itineraries?limit=100');
assert.equal(itineraries.response.status,200);
assert.equal(itineraries.result.totalDocs,9);
const denied=await request('/cms-api/leads');
assert.equal(denied.response.status,403);
const privateDenied=await request('/cms-api/private-files');
assert.equal(privateDenied.response.status,403);
const invalid=await request('/api/callback-requests',post({name:'Invalid'}));
assert.equal(invalid.response.status,400);
const lead=await request('/api/callback-requests',post({name:'CMS verification fixture',phone:'9999999999',title:'Test enquiry',adults:'2',children:'1'}));
assert.equal(lead.response.status,201);
const saved=await request(`/cms-api/leads/${lead.result.id}`,{headers:authorization});
assert.equal(saved.result.name,'CMS verification fixture');
assert.equal(saved.result.children,1);
await request(`/cms-api/leads/${lead.result.id}`,{method:'DELETE',headers:authorization});
const email=`cms-check-${randomUUID()}@example.com`;
const signup=await request('/api/account/register',post({name:'CMS check',email,phone:'9999999999',callingCode:'+91',password:'TestPassword123!',terms:'on',role:'admin'}));
assert.equal(signup.response.status,200);
assert.ok(signup.response.headers.get('set-cookie')?.includes('HttpOnly'));
const user=await request(`/cms-api/users/${signup.result.user.id}`,{headers:authorization});
assert.equal(user.result.role,'customer');
const customerLogin=await request('/api/account/login',post({identifier:email,password:'TestPassword123!'}));
assert.equal(customerLogin.response.status,200);
await request(`/cms-api/users/${signup.result.user.id}`,{method:'DELETE',headers:authorization});
const previousMedia=await request('/cms-api/media?where[alt][equals]=CMS%20upload%20verification%20fixture',{headers:authorization});
for(const fixture of previousMedia.result.docs)await request(`/cms-api/media/${fixture.id}`,{method:'DELETE',headers:authorization});
const imageBytes=await readFile('public/figma/imgImage8.png');
const mediaForm=new FormData();
mediaForm.set('_payload',JSON.stringify({alt:'CMS upload verification fixture'}));
mediaForm.set('file',new File([imageBytes],'cms-check.png',{type:'image/png'}));
const media=await request('/cms-api/media',{method:'POST',headers:authorization,body:mediaForm});
assert.equal(media.response.status,201);
assert.ok(media.result.doc.sizes.card.url);
assert.ok((await fetch(base+new URL(media.result.doc.url,base).pathname)).ok);
await request(`/cms-api/media/${media.result.doc.id}`,{method:'DELETE',headers:authorization});
const applicationForm=new FormData();
for(const [key,value] of Object.entries({type:'application',name:'CMS upload fixture',email:'test@example.com',phone:'9999999999',position:'Test position'}))applicationForm.set(key,value);
const stream='BT /F1 12 Tf 50 750 Td (CMS upload test fixture) Tj ET';
const objects=['<< /Type /Catalog /Pages 2 0 R >>','<< /Type /Pages /Kids [3 0 R] /Count 1 >>','<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'];
let pdf='%PDF-1.4\n';const offsets=[0];
for(const [index,object] of objects.entries()){offsets.push(Buffer.byteLength(pdf));pdf+=`${index+1} 0 obj\n${object}\nendobj\n`;}
const xref=Buffer.byteLength(pdf);
pdf+=`xref\n0 6\n0000000000 65535 f \n${offsets.slice(1).map(offset=>String(offset).padStart(10,'0')+' 00000 n ').join('\n')}\ntrailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
applicationForm.set('resume',new File([pdf],'fixture.pdf',{type:'application/pdf'}));
const application=await request('/api/contact-requests',{method:'POST',headers:{Origin:base},body:applicationForm});
assert.equal(application.response.status,201);
const savedApplication=await request(`/cms-api/applications/${application.result.id}`,{headers:authorization});
const resumeId=savedApplication.result.resume.id;
const publicResume=await fetch(base+new URL(savedApplication.result.resume.url,base).pathname);
assert.equal(publicResume.status,403);
await request(`/cms-api/applications/${application.result.id}`,{method:'DELETE',headers:authorization});
await request(`/cms-api/private-files/${resumeId}`,{method:'DELETE',headers:authorization});
console.log('CMS checks passed: PostgreSQL content, admin authentication, private access, validation, lead persistence, customer registration and privilege protection.');
